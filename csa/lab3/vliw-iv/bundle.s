; ============================================================
; Program: FNV-1 32-bit hash
; Программа: вычисление 32-битного FNV-1 хэша
;
; Input / Вход:
;   memory-mapped input port 0x80
;   поток чисел-кодов символов, заканчивающийся 0
;   пример: [97, 98, 99, 0] соответствует строке "abc\0"
;
; Output / Выход:
;   memory-mapped output port 0x84
;   одно 32-битное число — итоговый FNV-1 hash
;
; Main idea / Основная идея:
;   hash = 0x811C9DC5
;   while current_char != 0:
;       hash = hash * 0x01000193
;       hash = hash XOR current_char
;
; Это именно FNV-1, потому что сначала выполняется multiply,
; а потом XOR. В FNV-1a порядок был бы обратным.
;
; Register usage / Назначение регистров:
;   t0 = input port address, адрес входного порта 0x80
;   t1 = output port address, адрес выходного порта 0x84
;   t2 = FNV prime, константа 0x01000193
;   s1 = hash value, текущее значение хэша
;   t4 = current character, текущий символ
;   t5 = temporary product, hash * FNV prime
;   t6 = next character, следующий символ
;
; VLIW-IV bundle format / Формат bundle:
;   ALU1 / ALU2 / MEM / CTRL
; ============================================================


.data
in_port_ptr:    .word 0x80          ; адрес входного MMIO-порта
out_port_ptr:   .word 0x84          ; адрес выходного MMIO-порта
fnv32_prime:    .word 0x01000193    ; FNV prime для 32-bit hash
fnv32_offset:   .word 0x811C9DC5    ; начальное значение hash, offset basis


.text
.org 0x88
_start:

    ; --------------------------------------------------------
    ; Bundle 1
    ; ALU1: LUI — Load Upper Immediate / загрузка старшей части immediate
    ;       Загружает в t0 старшую часть адреса метки in_port_ptr.
    ;       Пока t0 содержит не 0x80, а адрес переменной in_port_ptr по частям.
    ;
    ; ALU2: LUI — Load Upper Immediate / загрузка старшей части immediate
    ;       Загружает в t1 старшую часть адреса метки out_port_ptr.
    ;       Пока t1 содержит не 0x84, а адрес переменной out_port_ptr по частям.
    ;
    ; MEM:  NOP — No Operation / нет операции
    ;       Память на этом bundle не используется.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ; --------------------------------------------------------
    lui t0, %hi(in_port_ptr)      / lui t1, %hi(out_port_ptr)      / nop          / nop


    ; --------------------------------------------------------
    ; Bundle 2
    ; ALU1: ADDI — Add Immediate / сложение с immediate
    ;       Добавляет к t0 младшую часть адреса in_port_ptr.
    ;       После этого t0 = адрес переменной in_port_ptr.
    ;
    ; ALU2: ADDI — Add Immediate / сложение с immediate
    ;       Добавляет к t1 младшую часть адреса out_port_ptr.
    ;       После этого t1 = адрес переменной out_port_ptr.
    ;
    ; MEM:  NOP — No Operation / нет операции
    ;       Память на этом bundle не используется.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ; --------------------------------------------------------
    addi t0, t0, %lo(in_port_ptr) / addi t1, t1, %lo(out_port_ptr) / nop          / nop


    ; --------------------------------------------------------
    ; Bundle 3
    ; ALU1: LUI — Load Upper Immediate / загрузка старшей части immediate
    ;       Загружает в t2 старшую часть адреса метки fnv32_prime.
    ;       Пока t2 содержит адрес константы fnv32_prime по частям.
    ;
    ; ALU2: LUI — Load Upper Immediate / загрузка старшей части immediate
    ;       Загружает в s1 старшую часть адреса метки fnv32_offset.
    ;       Пока s1 содержит адрес константы fnv32_offset по частям.
    ;
    ; MEM:  LW — Load Word / загрузка слова из памяти
    ;       Загружает значение из памяти по адресу t0.
    ;       До команды: t0 = адрес переменной in_port_ptr.
    ;       В памяти там лежит 0x80.
    ;       После команды: t0 = 0x80.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ; --------------------------------------------------------
    lui t2, %hi(fnv32_prime)      / lui s1, %hi(fnv32_offset)      / lw t0, 0(t0) / nop


    ; --------------------------------------------------------
    ; Bundle 4
    ; ALU1: ADDI — Add Immediate / сложение с immediate
    ;       Добавляет к t2 младшую часть адреса fnv32_prime.
    ;       После этого t2 = адрес переменной fnv32_prime.
    ;
    ; ALU2: ADDI — Add Immediate / сложение с immediate
    ;       Добавляет к s1 младшую часть адреса fnv32_offset.
    ;       После этого s1 = адрес переменной fnv32_offset.
    ;
    ; MEM:  LW — Load Word / загрузка слова из памяти
    ;       Загружает значение из памяти по адресу t1.
    ;       До команды: t1 = адрес переменной out_port_ptr.
    ;       В памяти там лежит 0x84.
    ;       После команды: t1 = 0x84.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ; --------------------------------------------------------
    addi t2, t2, %lo(fnv32_prime) / addi s1, s1, %lo(fnv32_offset) / lw t1, 0(t1) / nop


    ; --------------------------------------------------------
    ; Bundle 5
    ; ALU1: NOP — No Operation / нет операции
    ;       Первый ALU-слот не используется.
    ;
    ; ALU2: NOP — No Operation / нет операции
    ;       Второй ALU-слот не используется.
    ;
    ; MEM:  LW — Load Word / загрузка слова из памяти
    ;       Загружает значение FNV prime.
    ;       До команды: t2 = адрес переменной fnv32_prime.
    ;       В памяти там лежит 0x01000193.
    ;       После команды: t2 = 0x01000193.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ; --------------------------------------------------------
    nop                           / nop                            / lw t2, 0(t2) / nop


    ; --------------------------------------------------------
    ; Bundle 6
    ; ALU1: NOP — No Operation / нет операции
    ;       Первый ALU-слот не используется.
    ;
    ; ALU2: NOP — No Operation / нет операции
    ;       Второй ALU-слот не используется.
    ;
    ; MEM:  LW — Load Word / загрузка слова из памяти
    ;       Загружает начальное значение hash.
    ;       До команды: s1 = адрес переменной fnv32_offset.
    ;       В памяти там лежит 0x811C9DC5.
    ;       После команды: s1 = 0x811C9DC5.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ; --------------------------------------------------------
    nop                           / nop                            / lw s1, 0(s1) / nop


    ; --------------------------------------------------------
    ; Bundle 7
    ; ALU1: NOP — No Operation / нет операции
    ;       Первый ALU-слот не используется.
    ;
    ; ALU2: NOP — No Operation / нет операции
    ;       Второй ALU-слот не используется.
    ;
    ; MEM:  LW — Load Word / загрузка слова из памяти
    ;       Читает первый символ из input port.
    ;       t0 = 0x80, поэтому чтение идёт из MMIO-порта 0x80.
    ;       После команды: t4 = первый символ входной строки.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ; --------------------------------------------------------
    nop                           / nop                            / lw t4, 0(t0) / nop


loop:

    ; --------------------------------------------------------
    ; Bundle 8
    ; ALU1: MUL — Multiply / умножение
    ;       Считает промежуточное значение FNV-1.
    ;       t5 = s1 * t2.
    ;       То есть t5 = hash_value * fnv32_prime.
    ;
    ; ALU2: NOP — No Operation / нет операции
    ;       Второй ALU-слот не используется.
    ;
    ; MEM:  NOP — No Operation / нет операции
    ;       Память на этом bundle не используется.
    ;
    ; CTRL: BEQZ — Branch If Equal Zero / переход, если равно нулю
    ;       Проверяет текущий символ.
    ;       Если t4 == 0, значит встретили конец C-style строки.
    ;       Тогда выполняется переход к метке end.
    ;
    ; Почему MUL и BEQZ можно поставить вместе:
    ;       MUL использует s1 и t2, записывает t5.
    ;       BEQZ использует t4.
    ;       Конфликта по регистрам нет.
    ;
    ; Если t4 == 0:
    ;       t5 может быть посчитан, но hash в s1 не изменится,
    ;       потому что XOR уже не выполнится.
    ; --------------------------------------------------------
    mul t5, s1, t2                / nop                            / nop          / beqz t4, end


    ; --------------------------------------------------------
    ; Bundle 9
    ; ALU1: XOR — Exclusive OR / побитовое исключающее ИЛИ
    ;       Обновляет hash по формуле FNV-1.
    ;       s1 = t5 XOR t4.
    ;       То есть hash_value = (hash_value * fnv32_prime) XOR current_char.
    ;
    ; ALU2: NOP — No Operation / нет операции
    ;       Второй ALU-слот не используется.
    ;
    ; MEM:  LW — Load Word / загрузка слова из памяти
    ;       Заранее читает следующий символ из input port.
    ;       t6 = следующий символ входной строки.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ;
    ; Почему следующий символ читается в t6, а не сразу в t4:
    ;       В этом же bundle команда XOR читает t4.
    ;       Если бы MEM-слот одновременно писал в t4,
    ;       возник бы read/write конфликт по t4.
    ;       Поэтому следующий символ временно кладётся в t6.
    ; --------------------------------------------------------
    xor s1, t5, t4                / nop                            / lw t6, 0(t0) / nop


    ; --------------------------------------------------------
    ; Bundle 10
    ; ALU1: MV — Move / копирование значения
    ;       Переносит следующий символ в регистр текущего символа.
    ;       t4 = t6.
    ;       Теперь ранее прочитанный next_char становится current_char.
    ;
    ; ALU2: NOP — No Operation / нет операции
    ;       Второй ALU-слот не используется.
    ;
    ; MEM:  NOP — No Operation / нет операции
    ;       Память на этом bundle не используется.
    ;
    ; CTRL: J — Jump / безусловный переход
    ;       Возвращает выполнение к метке loop.
    ;       Начинается следующая итерация цикла.
    ;
    ; Почему MV и J можно поставить вместе:
    ;       MV обновляет t4.
    ;       J просто меняет PC.
    ;       В следующей итерации loop уже будет использоваться новое значение t4.
    ; --------------------------------------------------------
    mv t4, t6                     / nop                            / nop          / j loop


end:

    ; --------------------------------------------------------
    ; Bundle 11
    ; ALU1: NOP — No Operation / нет операции
    ;       Первый ALU-слот не используется.
    ;
    ; ALU2: NOP — No Operation / нет операции
    ;       Второй ALU-слот не используется.
    ;
    ; MEM:  SW — Store Word / сохранение слова в память
    ;       Записывает итоговый hash в output port.
    ;       t1 = 0x84.
    ;       s1 = итоговое значение hash_value.
    ;       Поэтому sw s1, 0(t1) записывает hash в MMIO-порт 0x84.
    ;
    ; CTRL: NOP — No Operation / нет операции
    ;       Переход на этом bundle не используется.
    ; --------------------------------------------------------
    nop                           / nop                            / sw s1, 0(t1) / nop


    ; --------------------------------------------------------
    ; Bundle 12
    ; ALU1: NOP — No Operation / нет операции
    ;       Первый ALU-слот не используется.
    ;
    ; ALU2: NOP — No Operation / нет операции
    ;       Второй ALU-слот не используется.
    ;
    ; MEM:  NOP — No Operation / нет операции
    ;       Память на этом bundle не используется.
    ;
    ; CTRL: HALT — Halt / остановка программы
    ;       Завершает выполнение программы.
    ; --------------------------------------------------------
    nop                           / nop                            / nop          / halt


; ============================================================
; Summary / Итоговое описание программы
;
; Эта программа реализует алгоритм FNV-1 32-bit hash.
;
; На вход поступает поток кодов символов через MMIO-порт 0x80.
; Поток должен быть C-style строкой, то есть заканчиваться нулём.
;
; Пример входа:
;   [97, 98, 99, 0]
;
; Это соответствует строке:
;   "abc\0"
;
; Программа не хранит индекс it, как в Python.
; Вместо этого она читает символы последовательно из input port 0x80.
;
; Начальное значение hash:
;   0x811C9DC5
;
; FNV prime:
;   0x01000193
;
; Для каждого ненулевого символа программа выполняет:
;   1. hash = hash * FNV prime
;   2. hash = hash XOR current_char
;
; Когда встречается символ 0, цикл завершается.
; Нулевой символ не включается в hash.
;
; Итоговое значение hash записывается в MMIO-порт 0x84.
;
; Главная идея VLIW-реализации:
;   независимые операции помещаются в один bundle.
;
; Например:
;   - умножение hash * prime выполняется параллельно с проверкой t4 на 0;
;   - XOR для обновления hash выполняется параллельно с чтением следующего символа.
;
; Это уменьшает количество bundle на одну итерацию цикла
; и лучше использует возможности VLIW-IV.
; ============================================================